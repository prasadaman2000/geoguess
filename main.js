var seenIdxs = new Set();
function start() {
  if (seenIdxs.size == images.length) {
    alert("No more images! Refresh the page to start over.");
    return;
  }

  var idx = Math.trunc(Math.random() * images.length);
  while (seenIdxs.has(idx)) {
    idx = Math.trunc(Math.random() * images.length);
  }
  seenIdxs.add(idx);
  currImage = images[idx];
  document.getElementById("thePicture").setAttribute("src", currImage["path"]);
  document.getElementById("startButton").setAttribute("hidden", "true");
  document.getElementById("resultDiv").setAttribute("hidden", "true");
  document.getElementById("showLast").setAttribute("hidden", "true");
  document.getElementById("map").removeAttribute("hidden");
  document.getElementById("submitButton").removeAttribute("hidden");
  map.invalidateSize();
  map.setView([37.423458148808685, -122.06666867333563], 10)
  if (marker != "") {
    marker.remove();
  }
  if (actualMarker != "") {
    actualMarker.remove();
  }
  gameInProgress = true;
}

function dayDiff() {
  var enteredDate = new Date(document.getElementById("dateOfImage").value);
  var diffMs = Math.abs(enteredDate - currImage["date"]);
  return (diffMs / (1000 * 60 * 60 * 24));
}

function latLongToRadians(latlong) {
  return {
    "lat": (latlong["lat"] * Math.PI) / 180,
    "long": (latlong["long"] * Math.PI) / 180,
  }
}

function latLongToXYZCoordinates(latlong) {
  return {
    "x": kEarthRadius * Math.sin(latlong["lat"]) * Math.cos(latlong["long"]),
    "y": kEarthRadius * Math.sin(latlong["lat"]) * Math.sin(latlong["long"]),
    "z": kEarthRadius * Math.cos(latlong["lat"])
  }
}

function distDiff() {
  console.log(lastClick)
  console.log(currImage["location"])

  var guessCoordinates = latLongToXYZCoordinates(latLongToRadians(lastClick));
  var actualCoordinates = latLongToXYZCoordinates(latLongToRadians(currImage["location"]));

  console.log(guessCoordinates)
  console.log(actualCoordinates)

  var deltas = {
    "x": guessCoordinates["x"] - actualCoordinates["x"],
    "y": guessCoordinates["y"] - actualCoordinates["y"],
    "z": guessCoordinates["z"] - actualCoordinates["z"],
  }

  console.log(deltas);

  return Math.sqrt(deltas["x"] * deltas["x"] + deltas["y"] * deltas["y"] + deltas["z"] * deltas["z"]);
}

